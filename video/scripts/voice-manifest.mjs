// Usage: node scripts/voice-manifest.mjs
// Reads public/voice/<composition>/NN.mp3 and the line times in scripts/voice-lines.json, writes src/voice-manifest.ts.
import fs from "node:fs";
import path from "node:path";
const lines = JSON.parse(fs.readFileSync("scripts/voice-lines.json", "utf8"));
const out = {};
for (const [comp, entries] of Object.entries(lines)) {
  const dir = path.join("public/voice", comp);
  const clips = entries.map((e, i) => ({ src: `voice/${comp}/${String(i + 1).padStart(2, "0")}.mp3`, at: e.at })).filter((c) => fs.existsSync(path.join("public", c.src)));
  if (clips.length) out[comp] = clips;
}
fs.writeFileSync("src/voice-manifest.ts", `/**\n * Voice clips per composition, placed at the second their line appears. Generated by\n * \`scripts/voice-manifest.mjs\` from the files in public/voice; do not edit by hand.\n */\nexport const VOICE: Record<string, { src: string; at: number }[]> = ${JSON.stringify(out, null, 2)};\n`);
console.log(Object.keys(out).map((k) => `${k}: ${out[k].length}`).join("\n") || "no clips yet");
