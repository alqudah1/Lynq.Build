// Generates docs/MEDIA-AUDIT.md from measurements, not from memory.
//
// Reads .audit/site-audit.json (every rendered image at every breakpoint,
// with its decoded size and display size) and the files on disk, and grades
// each production asset against the original it came from.
//
// Usage: node scripts/audit-site.mjs && node scripts/build-media-audit.mjs
import { readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import sharp from "sharp";

const audit = JSON.parse(readFileSync(".audit/site-audit.json", "utf8"));
const SRC = "../../03_Images";

// Collapse every appearance of an asset to its worst case across breakpoints.
const assets = new Map();
for (const page of audit) {
  for (const img of page.imgs) {
    const file = decodeURIComponent(img.src).replace(/^.*url=/, "").split("&")[0];
    const key = file;
    const prev = assets.get(key) ?? { file, uses: [], maxDisp: 0, natW: img.natW, worst: 0, broken: false };
    prev.uses.push(`${page.route}@${page.vp}`);
    prev.maxDisp = Math.max(prev.maxDisp, img.dispW);
    prev.natW = Math.max(prev.natW, img.natW);
    prev.worst = Math.max(prev.worst, img.upscale ?? 0);
    prev.broken = prev.broken || img.broken;
    assets.set(key, prev);
  }
}

function originalFor(file) {
  const m = file.match(/DSC\d+/);
  if (!m) return null;
  const p = `${SRC}/${m[0]}.JPG`;
  return existsSync(p) ? p : null;
}

const rows = [];
for (const a of [...assets.values()].sort((x, y) => y.worst - x.worst)) {
  const local = `public${a.file.split("?")[0]}`;
  let dims = "n/a", bytes = 0, alpha = false;
  if (existsSync(local)) {
    const m = await sharp(local).metadata();
    dims = `${m.width}x${m.height}`; alpha = Boolean(m.hasAlpha);
    bytes = statSync(local).size;
  }
  const orig = originalFor(a.file);
  let origDims = "";
  if (orig) { const om = await sharp(orig).metadata(); origDims = `${om.width}x${om.height}`; }
  const grade = a.broken ? "FAIL" : a.worst > 1.35 ? "C" : a.worst > 1.12 ? "B" : "A";
  rows.push({ ...a, dims, bytes, alpha, orig: orig ? orig.split("/").pop() : "(derived/none)", origDims, grade });
}

const counts = rows.reduce((m, r) => ((m[r.grade] = (m[r.grade] ?? 0) + 1), m), {});
const md = [];
md.push("# Media audit");
md.push("");
md.push("Generated by `scripts/build-media-audit.mjs` from `scripts/audit-site.mjs`, which");
md.push("loads every page in a real browser at 375, 768 and 1440 and records each image's");
md.push("DECODED size against its DISPLAYED size. Upscale is measured, not estimated.");
md.push("");
md.push(`Assets in production: **${rows.length}**`);
md.push("");
md.push("| Grade | Meaning | Count |");
md.push("|---|---|---|");
md.push(`| A | Never upscaled anywhere (<= 1.12x) | ${counts.A ?? 0} |`);
md.push(`| B | Mild upscale at one breakpoint (1.12x to 1.35x) | ${counts.B ?? 0} |`);
md.push(`| C | Visibly weak, upscaled beyond 1.35x | ${counts.C ?? 0} |`);
md.push(`| FAIL | Broken or not loading | ${counts.FAIL ?? 0} |`);
md.push("");
md.push("| Asset | Dimensions | Max display | Upscale | Alpha | KB | Original | Original size | Grade |");
md.push("|---|---|---|---|---|---|---|---|---|");
for (const r of rows) {
  md.push(`| \`${r.file.split("/").pop()}\` | ${r.dims} | ${r.maxDisp}px | ${r.worst ? r.worst.toFixed(2) + "x" : "n/a"} | ${r.alpha ? "yes" : "no"} | ${Math.round(r.bytes / 1024)} | ${r.orig} | ${r.origDims || "n/a"} | ${r.grade} |`);
}
md.push("");
md.push("## Rebuild history");
md.push("");
md.push("- **Cut-outs** were 1200px and are now **2400px**, rebuilt by `scripts/build-hires.mjs`.");
md.push("  Colour comes from the 6000x4000 original; the matte is still computed by the proven");
md.push("  1600px path and resized up to meet it, because a soft mask survives a resize and");
md.push("  stitch detail does not.");
md.push("- **Tile cut-outs** (de-haloed, for colour fields) now derive from those 2400px cuts.");
md.push("- **Macros** were cropped from an already-downscaled 1600px proxy and then upscaled to");
md.push("  1100px, i.e. roughly 430px of real detail. `scripts/build-textures.mjs` now crops the");
md.push("  full-resolution original and downsamples. A dedicated wider `macro-metallic` (1937px)");
md.push("  serves the homepage material moment.");
md.push("- **Wordmarks** were re-keyed from the client's 2646x756 artwork with flat ink and true");
md.push("  alpha (`scripts/build-logo.mjs`). Note the mark's own ink occupies only ~1106px of that");
md.push("  canvas, so its true resolution was never the limiting factor.");
md.push("");
md.push("## Sources");
md.push("");
md.push("`03_Images/` holds 45 originals at 6000x4000, EXIF orientation 8. No video exists");
md.push("anywhere in the client archive. `02_Branding/` holds the two logo files. No other");
md.push("client folder contains product media.");
writeFileSync("docs/MEDIA-AUDIT.md", md.join("\n") + "\n");
console.log(`docs/MEDIA-AUDIT.md written: ${rows.length} assets, A=${counts.A ?? 0} B=${counts.B ?? 0} C=${counts.C ?? 0} FAIL=${counts.FAIL ?? 0}`);
