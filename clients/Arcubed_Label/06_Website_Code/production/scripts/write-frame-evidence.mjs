// Regenerates the frame-level evidence table inside PRODUCT-GEOMETRY-MAP.md
// (the canonical evidence document) from .blockouts/measurements.json.
// Content lives between the AUTOGEN markers; everything outside is hand-written.
// Run after scripts/measure-products.mjs.
import { readFileSync, writeFileSync } from "node:fs";

const M = JSON.parse(readFileSync(".blockouts/measurements.json", "utf8"));
const DOC = "docs/3d-production/PRODUCT-GEOMETRY-MAP.md";
const START = "<!-- AUTOGEN:FRAME-EVIDENCE START -->";
const END = "<!-- AUTOGEN:FRAME-EVIDENCE END -->";

// What each frame is judged to prove. A near-front frame proves the front
// silhouette and nothing about depth; a three-quarter frame proves depth
// exists but yields no ratio.
const THREE_QUARTER = new Set(["DSC04876", "DSC04877", "DSC04878", "DSC05770", "DSC05773", "DSC05775", "DSC05787", "DSC04865", "DSC04867", "DSC05785", "DSC05781"]);
const NAMES = { vault: "Vault", "mini-luna": "Mini Luna", loco: "Loco", nova: "Nova" };
const ATTRIB = {
  vault: "CONFIRMED BY RAND (DSC04876 named in the archive audit); remaining frames CONFIRMED FROM PHOTOS by identical construction",
  "mini-luna": "CONFIRMED BY RAND (DSC05774 named); DSC04870-04875 CONFIRMED FROM PHOTOS — identical silhouette plus an exact match to Mini Luna's confirmed colour list",
  loco: "CONFIRMED BY RAND (DSC05765 named); remaining frames CONFIRMED FROM PHOTOS by identical fringe construction",
  nova: "UNRESOLVED — the archive audit named 'Gold Nova photography' with no file numbers. These 22 frames form one distinct shape family that no other product fits, but no frame is client-confirmed",
};

let out = `${START}\n\n`;
out += `> Regenerated by \`scripts/write-frame-evidence.mjs\` from\n`;
out += `> \`.blockouts/measurements.json\`. Do not hand-edit between the markers.\n`;
out += `> Every measurement was taken **after** EXIF orientation normalization\n`;
out += `> (all 45 frames are orientation=8 — see §0.3).\n\n`;

for (const [key, rows] of Object.entries(M)) {
  const ok = rows.filter((r) => !r.error);
  out += `### ${NAMES[key]} — ${ok.length} frames\n\n`;
  out += `**Product attribution:** ${ATTRIB[key]}\n\n`;
  out += `| Frame | View | Orient. normalized | Total W:H | Body W:H | Through-opening | Proves | Does NOT prove |\n`;
  out += `|---|---|---|---|---|---|---|---|\n`;
  for (const r of ok) {
    const tq = THREE_QUARTER.has(r.frame);
    const view = tq ? "three-quarter" : "near-front";
    const open = r.openingDetected
      ? `yes — ${(r.openingAreaFrac * 100).toFixed(1)}% of box, bottom at ${(r.handleHeightFrac * 100).toFixed(0)}%`
      : "none detected";
    const proves = tq
      ? "that the product has real depth and a rounded back"
      : "front silhouette; body:handle proportion";
    const notProves = tq
      ? "any ratio (foreshortened — never averaged into a W:H figure)"
      : "depth · back · base · hardware · strap/chain anchors";
    out += `| \`${r.frame}\` | ${view} | yes | ${r.totalWidthHeight.toFixed(2)} | ${r.bodyWidthHeight.toFixed(2)} | ${open} | ${proves} | ${notProves} |\n`;
  }
  const front = ok.filter((r) => !THREE_QUARTER.has(r.frame));
  const bodies = front.map((r) => r.bodyWidthHeight).sort((a, b) => a - b);
  if (bodies.length) {
    out += `\n**Near-front body W:H:** min ${bodies[0].toFixed(2)} · median ${bodies[bodies.length >> 1].toFixed(2)} · max ${bodies[bodies.length - 1].toFixed(2)} `;
    out += `(${front.length} frames; three-quarter frames excluded from this figure by design)\n\n`;
  }
}
out += `\n**Media type:** every row above is a still JPEG. **No video exists in this\n`;
out += `project.** The archive's 2025 "Arcubed Phone Vids" and 2026 "VIDEOS"\n`;
out += `folders were never downloaded, so no motion evidence could be examined —\n`;
out += `which is why Loco's fringe attachment remains unresolved.\n\n${END}`;

const doc = readFileSync(DOC, "utf8");
const i = doc.indexOf(START), j = doc.indexOf(END);
const next = i >= 0 && j > i ? doc.slice(0, i) + out + doc.slice(j + END.length) : doc + "\n\n## Frame-level evidence (generated)\n\n" + out + "\n";
writeFileSync(DOC, next);
console.log(`Wrote frame evidence for ${Object.keys(M).length} products into ${DOC}`);
